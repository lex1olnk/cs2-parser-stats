/**
 * HLTV Rating 2.0 — тот же рейтинг, который показывает FACEIT в статистике
 * матча.
 *
 *   Impact = 2.13*KPR + 0.42*APR - 0.41
 *   Rating = 0.0073*KAST + 0.3591*KPR - 0.5329*DPR
 *          + 0.2372*Impact + 0.0032*ADR + 0.1587
 *
 * Раньше в проекте считалось
 *   0.3591*KPR + 0.4778*SPR + 0.3658*RMK - 0.394*DPR + 0.2778
 * и подписывалось как «HLTV Rating 1.0». Настоящей 1.0 это не было:
 * коэффициент при KPR взят из регрессии 2.0, остальные слагаемые ни к одной
 * из формул не относятся. На проверенном матче игрок с 43 убийствами при
 * 23 смертях получал 0.76 — то есть лидерборд показывал, что все играют плохо.
 *
 * Компоненты складываются по матчам, и только потом применяется формула:
 * усреднять готовые рейтинги за матч нельзя, она нелинейна по раундам.
 */
/**
 * Меньше этого числа раундов — игрок не попадает в рейтинги и сравнения.
 *
 * Без порога любая таблица бессмысленна: человек с двумя раундами, одним
 * убийством и одним хедшотом получает 100% в голову, K/D равный числу
 * убийств (делить не на что) и первое место сразу по нескольким колонкам.
 * Порог примерно в полтора матча — достаточно, чтобы случайность не
 * выносило наверх, и достаточно мало, чтобы новичок не ждал вечно.
 */
export const MIN_RANKED_ROUNDS = 30;

export type RatingTotals = {
  kills: number;
  deaths: number;
  assists: number;
  damage: number;
  kastRounds: number;
  rounds: number;
};

export function ratingComponents(totals: RatingTotals) {
  const rounds = Math.max(totals.rounds, 1);
  const kpr = totals.kills / rounds;
  const dpr = totals.deaths / rounds;
  const apr = totals.assists / rounds;
  const adr = totals.damage / rounds;
  const kast = (totals.kastRounds / rounds) * 100;

  const impact = 2.13 * kpr + 0.42 * apr - 0.41;
  const rating =
    0.0073 * kast +
    0.3591 * kpr -
    0.5329 * dpr +
    0.2372 * impact +
    0.0032 * adr +
    0.1587;

  return { kpr, dpr, apr, adr, kast, impact, rating };
}

/**
 * То же выражение на SQL — для сортировки прямо в запросе, чтобы не тянуть
 * всех игроков в приложение ради упорядочивания. `a` — алиас таблицы
 * с просуммированными компонентами.
 */
export const RATING_SQL_ORDER = `
    0.0073 * (a.kast_rounds::float / GREATEST(a.rounds, 1) * 100)
  + 0.3591 * (a.kills::float   / GREATEST(a.rounds, 1))
  - 0.5329 * (a.deaths::float  / GREATEST(a.rounds, 1))
  + 0.2372 * (2.13 * (a.kills::float   / GREATEST(a.rounds, 1))
            + 0.42 * (a.assists::float / GREATEST(a.rounds, 1)) - 0.41)
  + 0.0032 * (a.damage::float  / GREATEST(a.rounds, 1))
  + 0.1587`;

/**
 * Рейтинг в духе FACEIT: линейная функция вклада в исход раундов.
 *
 * ГЛАВНОЕ, ЧТО УДАЛОСЬ УСТАНОВИТЬ. Рейтинг FACEIT — это почти в точности
 * линейная функция их же колонки Swing. По 80 игрокам из восьми матчей:
 *
 *     rating = 1.109 + 0.0604 * swing      RMSE 0.026
 *
 * Кривизны нет даже на краях: Burrr5a со swing 15.52 получил 2.05, линейная
 * модель даёт 2.04. Но связь не идеальна: в восьмом матче wait со swing
 * -5.40 получил 0.80, а SWAMPGOD со swing -4.05 — только 0.77, то есть
 * порядок местами нарушается. Остаток проверен против всех остальных колонок
 * их таблицы (K, D, A, ADR, HS%, мультикиллы, MVP, число раундов): ни одна
 * не коррелирует с ним выше 0.09, и вне выборки любое второе слагаемое
 * делает только хуже. Значит это хвост в ±0.1, а не пропущенный фактор.
 *
 * Отсюда следует важное: 0.026 — это ПОЛ для любой модели, которая идёт
 * через swing. Наша ошибка около 0.11 почти целиком сидит не в форме
 * формулы, а в том, что наш swing отличается от их swing. Улучшать надо
 * оценку swing, а не подбирать слагаемые к рейтингу.
 *
 * ПОЧЕМУ ЗДЕСЬ БОЛЬШЕ НЕТ СЛАГАЕМЫХ. К swing по очереди пробовались клатчи
 * и урон утилитой. Оба сначала помогали, а с ростом выборки переставали:
 *
 *   вне выборки        6 матчей   7 матчей
 *   только swing         0.095      0.109
 *   swing + утилита      0.091      0.110
 *   swing + клатчи       0.113      0.119
 *
 * Оба были заплатками поверх ошибки в swing, а не самостоятельными
 * факторами. Раз рейтинг линеен по их swing с точностью 0.025, места для
 * дополнительных слагаемых в нём попросту нет. Работа поэтому ушла целиком
 * в модель шансов — и первое же, что там нашлось, это экономика: учёт
 * стоимости снаряжения опустил ошибку рейтинга с 0.116 до 0.113.
 *
 * НАШ SWING ВСЁ ЕЩЁ РАСТЯНУТ: их swing = 0.89 * наш (было 0.80 до учёта
 * экономики). Масштаб поглощается коэффициентом при подгонке, поэтому
 * отдельно его не правим. Оставшийся разрыв до 0.025 — это по-прежнему шум
 * в оценке swing; следующий кандидат на объяснение — карта в состоянии
 * раунда, но на неё нужно порядка двух десятков матчей на каждую карту.
 *
 * ГДЕ МЫ СЕЙЧАС. По семи матчам FACEIT, 70 игроков: расхождение с их
 * колонкой Swing 1.83 пункта при корреляции 0.94, ошибка рейтинга 0.106
 * в выборке и 0.108 на матче, которого модель не видела.
 *
 * ВАЖНО: swing считает парсер (cs-parser/swing-model.js), и у матчей,
 * залитых до его появления, он отсутствует. Для них честнее вернуть
 * HLTV 2.0, чем показывать рейтинг, посчитанный из пустоты.
 */
const IMPACT_INTERCEPT = 1.105;
const IMPACT_PER_SWING = 5.176;

export function impactRating(
  totals: RatingTotals & { swing?: number | null }
) {
  if (totals.swing === null || totals.swing === undefined) {
    return { rating: ratingComponents(totals).rating, source: "hltv2" as const };
  }

  const rounds = Math.max(totals.rounds, 1);
  return {
    rating: IMPACT_INTERCEPT + IMPACT_PER_SWING * (totals.swing / rounds),
    source: "swing" as const,
  };
}
